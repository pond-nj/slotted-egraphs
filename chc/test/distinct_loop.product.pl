loopPair([], X_1, [], X1_2) :-
    X_1 = 0,
    X1_2 = 0.

loopPair([], X_1, [Z1_2|A01_2], J1_2) :-
    loopPair([], X_1, A01_2, J01_2),
    X_1 = 0,
    ((J1_2 > 0) & (J01_2 = J1_2 - 1)) & (Z1_2 = 0).

loopPair([Z_1|A0_1], J_1, [], X1_2) :-
    loopPair(A0_1, J0_1, [], X1_2),
    ((J_1 > 0) & (J0_1 = J_1 - 1)) & (Z_1 = 0),
    X1_2 = 0.

loopPair([Z_1|A0_1], J_1, [Z1_2|A01_2], J1_2) :-
    loopPair(A0_1, J0_1, A01_2, J01_2),
    ((J_1 > 0) & (J0_1 = J_1 - 1)) & (Z_1 = 0),
    ((J1_2 > 0) & (J01_2 = J1_2 - 1)) & (Z1_2 = 0).

